// Turns the sandbox into plain browser JavaScript, so a static page can run it.
// Usage: node scripts/build-playground.mjs <output directory>
// Re-run it after any sandbox change and commit the output where it is hosted.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { stripTypeScriptTypes } from 'node:module'

const out = process.argv[2]
if (!out) {
  console.error('Usage: node scripts/build-playground.mjs <output directory>')
  process.exit(1)
}
mkdirSync(out, { recursive: true })

const files = ['catalog', 'server', 'store', 'sandbox']
for (const name of files) {
  const source = readFileSync(join('sandbox', `${name}.ts`), 'utf8')
  const js = stripTypeScriptTypes(source, { mode: 'strip' }).replace(/(from\s+['"]\.\/[\w-]+)\.ts(['"])/g, '$1.js$2')
  if (/\.ts['"]/.test(js)) throw new Error(`${name}.ts still imports a .ts file`)
  writeFileSync(join(out, `${name}.js`), js)
}
// One entry per API operation, taken from the spec, so the page never lists an operation that does not exist.
const spec = JSON.parse(readFileSync(join('openapi', 'arena.json'), 'utf8'))
const operations = []
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue
    operations.push({ method: method.toUpperCase(), path, summary: op.summary, example: op['x-example'] ?? {} })
  }
}
writeFileSync(join(out, 'operations.js'), `// Generated by scripts/build-playground.mjs from openapi/arena.json. Do not edit.\nexport const OPERATIONS = ${JSON.stringify(operations, null, 2)}\n`)

console.log(`Wrote ${files.length + 1} files to ${out}`)
